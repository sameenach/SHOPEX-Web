export const metadata ={
  title: "Products",
  description: "Generated by create next app",
};
import {getProducts} from "../Services/ProductService"
import React from "react";
import Link from "next/link";
import "./product.css";

export default async function ProductList({ searchParams }) {
  const products = await getProducts();

  const { search = "", category = "", limit = "" } = await searchParams;

  let filteredProducts = products.filter((prod) =>
    prod.title.toLowerCase().includes(search.toLowerCase()) &&
    prod.category.toLowerCase().includes(category.toLowerCase())
  );

  if (limit) {
    filteredProducts = filteredProducts.slice(0, Number(limit));
  }

  return (
    <div className="product-page">
      <section className="product-banner">
        <p className="banner-tag">THE NEW COLLECTION</p>
        <h1>Discover Your Style</h1>
        <p>
          Explore our collection of trendy products
          picked just for you.
        </p>
      </section>

      <section className="products-section">
        <div className="section-heading">
          <div>
            <p className="section-subtitle">MADE FOR YOU</p>
            <h2>Our Products</h2>
          </div>

          <span className="product-count">
            {filteredProducts.length} Products
          </span>
        </div>

        <div className="products-container">
          {filteredProducts.length > 0 ? (
            filteredProducts.map((prod) => (
              <div className="product-card" key={prod.id}>
                <div className="product-image-container">
                  <span className="product-badge">
                    NEW ARRIVAL
                  </span>

                  <img
                    src={prod.image}
                    alt={prod.title}
                    className="product-image"
                  />
                </div>

                <div className="product-info">
                  <p className="product-category">
                    {prod.category}
                  </p>

                  <h3 className="product-title">
                    {prod.title}
                  </h3>

                  <p className="product-price">
                    ₹{Number(prod.price).toFixed(2)}
                  </p>

                  <Link
                    href={`/Product/${prod.id}`}
                    className="view-button"
                  >
                    View More <span>→</span>
                  </Link>
                </div>
              </div>
            ))
          ) : (
            <h2>No products found!</h2>
          )}
        </div>
      </section>
    </div>
  );
}
